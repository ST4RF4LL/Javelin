import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

let build;
try { ({ build } = await import('esbuild')); }
catch (error) {
  if (error.code !== 'ERR_MODULE_NOT_FOUND') throw error;
  console.error('监控构建依赖未安装完整。请在仓库根目录依次执行：\n'
    + 'npm --prefix apps/workbench ci --include=dev --include=optional\n'
    + 'npm --prefix apps/workbench run build\n'
    + `原始错误：${error.message}`);
  process.exit(1);
}

const root = new URL('../../../', import.meta.url);
const base = new URL('.opencode/web/dynamic-validation-observatory/', root);
const output = await build({
  entryPoints: [fileURLToPath(new URL('monitor/audit-monitor.js', base))],
  outfile: 'audit-monitor.js', bundle: true, format: 'iife', globalName: 'WorkbenchMonitor', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'inline', write: false,
  nodePaths: [fileURLToPath(new URL('../node_modules', import.meta.url))],
  define: { 'process.env.NODE_ENV': '"production"' },
});
for (const [extension, target] of [['js', 'app.js'], ['css', 'styles.css']]) {
  const asset = output.outputFiles.find(file => file.path.endsWith(`.${extension}`));
  if (!asset) throw new Error(`监控构建缺少 ${extension} 产物`);
  const path = new URL(`public/${target}`, base), content = await readFile(path, 'utf8');
  const start = '/* BEGIN GENERATED AUDIT MONITOR */', end = '/* END GENERATED AUDIT MONITOR */';
  const hash = createHash('sha256').update(asset.text).digest('hex');
  const block = `${start}\n/* audit-events + ttyd; sha256:${hash}; generated by build-audit-monitor.mjs */\n${asset.text}\n${end}`;
  const first = content.indexOf(start), last = content.indexOf(end);
  if ((first < 0) !== (last < 0) || (first >= 0 && last < first)) throw new Error(`${target} 的构建标记无效`);
  const next = first < 0 ? `${block}\n${content}` : content.slice(0, first) + block + content.slice(last + end.length);
  if (process.argv.includes('--check')) {
    if (next !== content) throw new Error(`${target} 监控产物未更新，请运行 npm run build:monitor`);
  } else if (next !== content) await writeFile(path, next);
  console.log(`${process.argv.includes('--check') ? '已核对' : '已生成'} ${target} 监控组件（${asset.contents.length} bytes）`);
}
